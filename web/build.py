#!/usr/bin/env python3
"""Build the web interface.

    python3 web/build.py            # fetch the design system release, then build
    python3 web/build.py --offline  # build from what was fetched before

Writes  web/dist/                  the page, ready to serve or to open from disk
        wifi/src/web_assets.h      the same files, gzipped, for the Wi-Fi module

The stylesheet, the fonts and the logo come from the latest release of the
design system (github.com/belikh/design). They are downloaded into
web/.design/ and are not committed, so a new release reaches the page at
the next build. Needs the `gh` command for the download.
"""
import base64
import gzip
import json
import shutil
import subprocess
import sys
import tarfile
from pathlib import Path

WEB = Path(__file__).resolve().parent
DESIGN = WEB / ".design"
DIST = WEB / "dist"
HEADER = WEB.parent / "wifi" / "src" / "web_assets.h"
REPO = "belikh/design"
LOGOS = ["jupiter-logo-light.svg", "jupiter-logo-dark.svg"]
MIME = {".html": "text/html; charset=utf-8", ".css": "text/css; charset=utf-8",
        ".js": "text/javascript; charset=utf-8", ".svg": "image/svg+xml",
        ".woff2": "font/woff2"}


def fetch() -> None:
    DESIGN.mkdir(exist_ok=True)
    subprocess.run(["gh", "release", "download", "--repo", REPO, "--dir", str(DESIGN),
                    "--clobber", "--pattern", "jupiter.css", "--pattern", "jupiter-fonts.css",
                    "--pattern", "jupiter-fonts.tgz"], check=True)
    for name in LOGOS:
        out = subprocess.run(["gh", "api", f"repos/{REPO}/contents/packages/graphics/logo/{name}"
                              "?ref=latest", "-q", ".content"], check=True,
                             capture_output=True, text=True).stdout
        (DESIGN / name).write_bytes(base64.b64decode(out))


def build() -> None:
    for need in ["jupiter.css", "jupiter-fonts.css", "jupiter-fonts.tgz", *LOGOS]:
        if not (DESIGN / need).exists():
            sys.exit(f"{need} is missing from {DESIGN}: run without --offline first")
    if DIST.exists():
        shutil.rmtree(DIST)
    (DIST / "fonts").mkdir(parents=True)
    for f in (WEB / "src").iterdir():
        shutil.copy(f, DIST / f.name)
    for name in ["jupiter.css", "jupiter-fonts.css", *LOGOS]:
        shutil.copy(DESIGN / name, DIST / name)
    with tarfile.open(DESIGN / "jupiter-fonts.tgz") as tar:
        for m in tar.getmembers():
            name = Path(m.name).name
            # the page sets nothing in italics, so those files stay out of the module's flash
            if name.endswith(".woff2") and "italic" not in name:
                (DIST / "fonts" / name).write_bytes(tar.extractfile(m).read())

    files = sorted(p for p in DIST.rglob("*") if p.is_file())
    out = ["// Generated by web/build.py. Do not edit.",
           "// The web interface, gzipped, for the Wi-Fi module to serve.",
           "#pragma once", "#include <Arduino.h>", ""]
    table = []
    total = 0
    for n, p in enumerate(files):
        rel = "/" + p.relative_to(DIST).as_posix()
        data = gzip.compress(p.read_bytes(), 9, mtime=0)
        total += len(data)
        body = ",".join(str(b) for b in data)
        out.append(f"static const uint8_t WEB_{n}[] PROGMEM = {{{body}}};")
        table.append(f'  {{{json.dumps(rel)}, {json.dumps(MIME[p.suffix])}, WEB_{n}, {len(data)}}},')
    out += ["", "struct WebAsset { const char *path; const char *mime; const uint8_t *data; size_t len; };",
            "static const WebAsset WEB_ASSETS[] = {", *table, "};",
            f"static const size_t WEB_ASSET_COUNT = {len(files)};", ""]
    HEADER.parent.mkdir(parents=True, exist_ok=True)
    HEADER.write_text("\n".join(out))
    print(f"{len(files)} files in {DIST}, {total} bytes gzipped in {HEADER.name}")


if __name__ == "__main__":
    if "--offline" not in sys.argv:
        fetch()
    build()
