"""Display assets from the design system: palette and bitmap fonts.

Reads   .design/jupiter.tokens.json            colour roles, device type sizes
        .design/package/files/jetbrains-mono.woff2
        rt-core/src/ui.rs                      the order of the colour roles
Writes  rt-hal/src/generated/assets.rs         palette and font tables
        rt-hal/src/generated/font_*.bin        glyphs, 2 bits per pixel

Run through ../update-design.sh. The output is not committed: it is made
again from each design system release, so no value is copied by hand.
"""
import io
import json
import re
from pathlib import Path

from fontTools.ttLib import TTFont
from PIL import Image, ImageDraw, ImageFont

ROOT = Path(__file__).resolve().parent.parent
DESIGN = ROOT / ".design"
OUT = ROOT / "rt-hal" / "src" / "generated"
FIRST, LAST = 32, 126
# which entry of the tokens' device type scale each display font uses
SIZES = {"small": 1, "body": 3, "big": 5}


def main() -> None:
    tokens = json.loads((DESIGN / "jupiter.tokens.json").read_text())
    scheme = tokens["color"]["dark"]            # displays use the dark scheme
    inks = re.search(r"INK_TOKENS: \[&str; \d+\] = \[(.*?)\];",
                     (ROOT / "rt-core" / "src" / "ui.rs").read_text(), re.S).group(1)
    names = re.findall(r'"(\w+)"', inks)
    rgb = [tuple(int(scheme[n][i:i + 2], 16) for i in (1, 3, 5)) for n in names]

    ttf = io.BytesIO()
    font = TTFont(DESIGN / "package" / "files" / "jetbrains-mono.woff2")
    font.flavor = None
    font.save(ttf)
    scale = tokens["device"]["fontSizes"]
    line = tokens["type"]["lineHeightHeading"]

    OUT.mkdir(parents=True, exist_ok=True)
    rs = [f"// Generated by assets/gen.py from design system {tokens['version']}. Do not edit.",
          "",
          f'pub const DESIGN_VERSION: &str = "{tokens["version"]}";',
          "",
          "/// RGB565 colour of each `rt_core::ui::Ink`, dark scheme.",
          f"pub const PALETTE: [u16; {len(rgb)}] = ["
          + ", ".join(f"0x{(r >> 3) << 11 | (g >> 2) << 5 | b >> 3:04x}" for r, g, b in rgb) + "];",
          "/// The same colours as 8-bit RGB, for previews on a PC.",
          f"pub const PALETTE_RGB: [[u8; 3]; {len(rgb)}] = ["
          + ", ".join(f"[{r}, {g}, {b}]" for r, g, b in rgb) + "];",
          "",
          "/// A monospaced bitmap font: glyphs for the characters FIRST..=LAST,",
          "/// each `w` x `h` pixels, 2 bits per pixel (0 = background, 3 = ink),",
          "/// row by row, four pixels to a byte, first pixel in the top bits.",
          "pub struct FontData {",
          "    pub w: u16,",
          "    pub h: u16,",
          "    pub glyph_bytes: usize,",
          "    pub data: &'static [u8],",
          "}",
          f"pub const FIRST: u8 = {FIRST};",
          f"pub const LAST: u8 = {LAST};",
          ""]
    for name, idx in SIZES.items():
        size = scale[idx]
        ttf.seek(0)
        f = ImageFont.truetype(ttf, size)
        w = round(f.getlength("M"))
        h = round(size * line)
        ascent, descent = f.getmetrics()
        top = (h - (ascent + descent)) // 2
        per = (w * h + 3) // 4
        blob = bytearray()
        for code in range(FIRST, LAST + 1):
            im = Image.new("L", (w, h), 0)
            ImageDraw.Draw(im).text((0, top), chr(code), font=f, fill=255)
            px = [min(3, (v + 42) // 85) for v in im.tobytes()]
            px += [0] * (per * 4 - len(px))
            for i in range(0, len(px), 4):
                blob.append(px[i] << 6 | px[i + 1] << 4 | px[i + 2] << 2 | px[i + 3])
        (OUT / f"font_{name}.bin").write_bytes(blob)
        rs += [f"/// JetBrains Mono at {size} px.",
               f"pub static {name.upper()}: FontData = FontData {{ w: {w}, h: {h}, "
               f"glyph_bytes: {per}, data: include_bytes!(\"font_{name}.bin\") }};"]
        print(f"{name}: {size} px, cell {w} x {h}, {len(blob)} bytes")
    (OUT / "assets.rs").write_text("\n".join(rs) + "\n")
    print(f"palette: {len(rgb)} inks from design system {tokens['version']}")


if __name__ == "__main__":
    main()
