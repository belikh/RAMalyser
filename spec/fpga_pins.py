"""FPGA ball assignment for the LFE5U-25F in caBGA256.

Bus lines sit on the left and right I/O banks (7, 6, 2, 3), ordered by ball
position so neighbouring bus lines escape the BGA side by side. Housekeeping
signals use the top banks. The same table drives the place-and-route
constraints (LPF) and the schematic generator.
"""
from __future__ import annotations

import sys
from pathlib import Path

ROWS = "ABCDEFGHJKLMNPRT"

# I/O balls per bank, from the Project Trellis database (LFE5U-25F, CABGA256).
BANK = {
    7: "B1 B2 C1 C2 C3 D1 D3 E1 E2 E3 F1 F2 F3 F4 F5 G1 G2 G3 G4 G5 H2 H3 H4 H5 "
       "J1 J2 J3 J4 J5 K1 K2 K3",
    6: "K4 K5 L1 L2 L3 L4 L5 M1 M2 M3 M4 M5 M6 N1 N3 N4 N5 N6 P1 P2 P3 P4 P5 P6 "
       "R1 R2 R3 R4 R5 T2 T3 T4",
    2: "B15 B16 C14 C15 C16 D14 D16 E14 E15 E16 F12 F13 F14 F15 F16 G12 G13 G14 "
       "G15 G16 H12 H13 H14 H15 J12 J13 J14 J15 J16 K14 K15 K16",
    3: "K12 K13 L12 L13 L14 L15 L16 M11 M12 M13 M14 M15 M16 N11 N12 N13 N14 N16 "
       "P11 P12 P13 P14 P15 P16 R12 R13 R14 R15 R16 T13 T14 T15",
}


def _key(ball: str) -> tuple[int, int]:
    return ROWS.index(ball[0]), int(ball[1:])


LEFT = sorted(BANK[7].split() + BANK[6].split(), key=_key)
RIGHT = sorted(BANK[2].split() + BANK[3].split(), key=_key)

# The card-edge socket runs left to right in front of the FPGA with the bus
# lines in order along it, so the left-hand balls take IO0..63 and the
# right-hand balls IO64..115.
IO_BALL = {}
for n, ball in enumerate(LEFT):
    IO_BALL[n] = ball
for n, ball in enumerate(RIGHT[:52]):
    IO_BALL[64 + n] = ball
SPARE_BALLS = RIGHT[52:]

# Balls the board cannot route, moved to a spare. R4 sits one row in from the
# corner with its four escape gaps taken on every layer, so IO59 uses T13 on
# the outer row. Both are full-featured bank I/O; per-line delay calibration
# absorbs the longer trace.
MOVED = {59: "T13"}
for n, ball in MOVED.items():
    assert ball in SPARE_BALLS, ball
    SPARE_BALLS = sorted([b for b in SPARE_BALLS if b != ball] + [IO_BALL[n]], key=_key)
    IO_BALL[n] = ball

# Non-I/O balls (Lattice pinout table for ECP5U-25, caBGA256).
FIXED_BALLS = {
    "GND": "A16 H16 T16 D15 N15 T12 G10 H10 J10 K10 F9 H9 J9 K9 F8 G8 H8 J8 K8 K7 K6 "
           "T5 D2 N2 A1 H1 T1",
    "VCC": "L10 G9 L9 L8 G7 G6",
    "VCCAUX": "G11 L7",
    "VCCIO": "F7 F6 F11 F10 H11 J11 K11 L11 J7 J6 H7 H6 L6",
    "CCLK": "N9", "CFG_0": "N10", "CFG_1": "P10", "CFG_2": "R10", "DONE": "P9",
    "INITN": "T9", "PROGRAMN": "R9", "TCK": "T10", "TDI": "R11", "TDO": "M10", "TMS": "T11",
}
# Bank 8 (configuration) I/O balls used for slave-SPI configuration.
CONFIG_IO = {"T8": "CFG_MOSI", "T7": "CFG_MISO", "R8": "CFG_SN", "N8": "CFG_HOLDN"}
TOP_BALLS = ("A2 A3 A4 A5 A6 A7 A8 B3 B4 B5 B6 B7 C4 C5 C6 C7 D4 D5 D6 D7 E4 E5 E6 E7 "
             "A10 A11 A12 A13 A14 A15 A9 B10 B11 B12 B13 B14 B8 B9 C10 C11 C12 C13 C8 C9 "
             "D10 D11 D12 D13 D8 D9 E10 E11 E12 E13 E8 E9").split()
BANK8_BALLS = "M7 M8 M9 N7 N8 P7 P8 R6 R7 R8 T6 T7 T8".split()


def all_balls() -> dict[str, str]:
    """Ball -> function name for all 256 balls."""
    out = {}
    for fn, balls in FIXED_BALLS.items():
        for b in balls.split():
            out[b] = fn
    for b in LEFT + RIGHT + TOP_BALLS + BANK8_BALLS:
        out[b] = f"IO_{b}"
    assert len(out) == 256, len(out)
    return out


HOUSEKEEPING = {
    "clk25": "A7",        # PCLKT0_0
    "spi_sck": "C8",      # PCLKT1_0
    "spi_cs_n": "A8",
    "spi_mosi": "A9",
    "spi_miso": "A10",
    "dut_pg": "B8",
    "busy": "B9",
    "pll_lock": "B10",
}


def lpf() -> str:
    out = ["# Generated by spec/fpga_pins.py - do not edit.", "BLOCK RESETPATHS;",
           "BLOCK ASYNCPATHS;", 'FREQUENCY PORT "clk25" 25 MHZ;']
    for name, ball in HOUSEKEEPING.items():
        out.append(f'LOCATE COMP "{name}" SITE "{ball}";')
        out.append(f'IOBUF PORT "{name}" IO_TYPE=LVCMOS33;')
    for n in range(116):
        out.append(f'LOCATE COMP "io[{n}]" SITE "{IO_BALL[n]}";')
        out.append(f'IOBUF PORT "io[{n}]" IO_TYPE=LVCMOS33 SLEWRATE=FAST DRIVE=8;')
    return "\n".join(out) + "\n"


if __name__ == "__main__":
    assert len(IO_BALL) == 116 and len(set(IO_BALL.values())) == 116
    all_balls()
    assert not set(IO_BALL.values()) & set(HOUSEKEEPING.values())
    Path(sys.argv[1]).write_text(lpf())
    print("lpf written:", sys.argv[1])
